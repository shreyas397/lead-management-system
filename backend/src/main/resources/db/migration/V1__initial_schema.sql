CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE leads (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES app_users(id),
 name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL,
 phone VARCHAR(30) NOT NULL,
 company VARCHAR(150) NOT NULL,
 service VARCHAR(100) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('NEW','CONTACTED','QUALIFIED','CONVERTED','LOST')),
 follow_up_date DATE,
 notes VARCHAR(4000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_leads_owner_created ON leads(owner_id, created_at);
CREATE INDEX idx_leads_owner_status ON leads(owner_id, status);
CREATE INDEX idx_leads_owner_follow_up ON leads(owner_id, follow_up_date);
